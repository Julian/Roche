use axum::{
    Json,
    extract::{
        FromRequest, FromRequestParts, Path, Query,
        rejection::{JsonRejection, PathRejection, QueryRejection, StringRejection},
    },
    http::{StatusCode, header},
    response::{IntoResponse, Response},
};
use serde::{Deserialize, Serialize};
use thiserror::Error;

/// RFC 9457 Problem Details for HTTP APIs (`application/problem+json`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProblemDetails {
    /// A URI reference that identifies the problem type.
    #[serde(rename = "type")]
    pub problem_type: String,
    /// A short, human-readable summary of the problem type.
    pub title: String,
    /// The HTTP status code generated by the origin server for this occurrence of the problem.
    pub status: u16,
    /// A human-readable explanation specific to this occurrence of the problem.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub detail: Option<String>,
    /// A URI reference that identifies the specific occurrence of the problem.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub instance: Option<String>,
}

impl ProblemDetails {
    #[must_use]
    pub fn new(
        status: StatusCode,
        problem_type: &str,
        title: &str,
        detail: impl Into<String>,
    ) -> Self {
        Self {
            problem_type: problem_type.to_string(),
            title: title.to_string(),
            status: status.as_u16(),
            detail: Some(detail.into()),
            instance: None,
        }
    }
}

/// Structured HTTP API errors backed by `thiserror` and rendered as RFC 9457 Problem Details.
#[derive(Debug, Error)]
pub enum ApiError {
    #[error("Bad request: {0}")]
    BadRequest(String),

    #[error("Unauthorized: {0}")]
    Unauthorized(String),

    #[error("Not found: {0}")]
    NotFound(String),

    #[error("Method not allowed: {0}")]
    MethodNotAllowed(String),

    #[error("Payload too large: {0}")]
    PayloadTooLarge(String),

    #[error("Unsupported media type: {0}")]
    UnsupportedMediaType(String),

    #[error("Too many requests: {0}")]
    TooManyRequests(String),

    #[error("Upstream fetch failed: {0}")]
    BadGateway(String),

    #[error("Database error: {0}")]
    Database(#[from] sqlx::Error),

    #[error("Internal error: {0}")]
    Internal(#[from] anyhow::Error),
}

impl ApiError {
    pub fn bad_request(message: impl Into<String>) -> Self {
        Self::BadRequest(message.into())
    }

    pub fn unauthorized(message: impl Into<String>) -> Self {
        Self::Unauthorized(message.into())
    }

    pub fn not_found(message: impl Into<String>) -> Self {
        Self::NotFound(message.into())
    }

    pub fn method_not_allowed(message: impl Into<String>) -> Self {
        Self::MethodNotAllowed(message.into())
    }

    pub fn too_many_requests(message: impl Into<String>) -> Self {
        Self::TooManyRequests(message.into())
    }

    pub fn bad_gateway(message: impl Into<String>) -> Self {
        Self::BadGateway(message.into())
    }

    #[must_use]
    pub fn to_problem_details(&self) -> (StatusCode, ProblemDetails) {
        match self {
            Self::BadRequest(detail) => (
                StatusCode::BAD_REQUEST,
                ProblemDetails::new(
                    StatusCode::BAD_REQUEST,
                    "urn:roche:problem:bad-request",
                    "Bad Request",
                    detail.clone(),
                ),
            ),
            Self::Unauthorized(detail) => (
                StatusCode::UNAUTHORIZED,
                ProblemDetails::new(
                    StatusCode::UNAUTHORIZED,
                    "urn:roche:problem:unauthorized",
                    "Unauthorized",
                    detail.clone(),
                ),
            ),
            Self::NotFound(detail) => (
                StatusCode::NOT_FOUND,
                ProblemDetails::new(
                    StatusCode::NOT_FOUND,
                    "urn:roche:problem:not-found",
                    "Not Found",
                    detail.clone(),
                ),
            ),
            Self::MethodNotAllowed(detail) => (
                StatusCode::METHOD_NOT_ALLOWED,
                ProblemDetails::new(
                    StatusCode::METHOD_NOT_ALLOWED,
                    "urn:roche:problem:method-not-allowed",
                    "Method Not Allowed",
                    detail.clone(),
                ),
            ),
            Self::PayloadTooLarge(detail) => (
                StatusCode::PAYLOAD_TOO_LARGE,
                ProblemDetails::new(
                    StatusCode::PAYLOAD_TOO_LARGE,
                    "urn:roche:problem:payload-too-large",
                    "Payload Too Large",
                    detail.clone(),
                ),
            ),
            Self::UnsupportedMediaType(detail) => (
                StatusCode::UNSUPPORTED_MEDIA_TYPE,
                ProblemDetails::new(
                    StatusCode::UNSUPPORTED_MEDIA_TYPE,
                    "urn:roche:problem:unsupported-media-type",
                    "Unsupported Media Type",
                    detail.clone(),
                ),
            ),
            Self::TooManyRequests(detail) => (
                StatusCode::TOO_MANY_REQUESTS,
                ProblemDetails::new(
                    StatusCode::TOO_MANY_REQUESTS,
                    "urn:roche:problem:too-many-requests",
                    "Too Many Requests",
                    detail.clone(),
                ),
            ),
            Self::BadGateway(detail) => (
                StatusCode::BAD_GATEWAY,
                ProblemDetails::new(
                    StatusCode::BAD_GATEWAY,
                    "urn:roche:problem:bad-gateway",
                    "Bad Gateway",
                    detail.clone(),
                ),
            ),
            Self::Database(sqlx_err) => Self::classify_sqlx_error(sqlx_err),
            Self::Internal(err) => {
                if let Some(sqlx_err) = err.downcast_ref::<sqlx::Error>() {
                    return Self::classify_sqlx_error(sqlx_err);
                }
                tracing::error!(error = %err, "Internal server error");
                (
                    StatusCode::INTERNAL_SERVER_ERROR,
                    ProblemDetails::new(
                        StatusCode::INTERNAL_SERVER_ERROR,
                        "urn:roche:problem:internal-error",
                        "Internal Server Error",
                        "An unexpected internal error occurred",
                    ),
                )
            }
        }
    }

    fn classify_sqlx_error(sqlx_err: &sqlx::Error) -> (StatusCode, ProblemDetails) {
        if let sqlx::Error::Database(db_err) = sqlx_err
            && (db_err.is_unique_violation()
                || db_err.message().contains("UNIQUE constraint failed"))
        {
            return (
                StatusCode::CONFLICT,
                ProblemDetails::new(
                    StatusCode::CONFLICT,
                    "urn:roche:problem:conflict",
                    "Conflict",
                    "A resource with the same unique identifier already exists",
                ),
            );
        }
        tracing::error!(error = %sqlx_err, "Database error");
        (
            StatusCode::INTERNAL_SERVER_ERROR,
            ProblemDetails::new(
                StatusCode::INTERNAL_SERVER_ERROR,
                "urn:roche:problem:internal-error",
                "Internal Server Error",
                "An unexpected database error occurred",
            ),
        )
    }
}

impl From<JsonRejection> for ApiError {
    fn from(rejection: JsonRejection) -> Self {
        match rejection {
            JsonRejection::MissingJsonContentType(err) => {
                Self::UnsupportedMediaType(err.body_text())
            }
            JsonRejection::BytesRejection(err) if err.status() == StatusCode::PAYLOAD_TOO_LARGE => {
                Self::PayloadTooLarge(err.body_text())
            }
            other => Self::BadRequest(other.body_text()),
        }
    }
}

impl From<StringRejection> for ApiError {
    fn from(rejection: StringRejection) -> Self {
        if rejection.status() == StatusCode::PAYLOAD_TOO_LARGE {
            Self::PayloadTooLarge(rejection.body_text())
        } else {
            Self::BadRequest(rejection.body_text())
        }
    }
}

impl From<QueryRejection> for ApiError {
    fn from(rejection: QueryRejection) -> Self {
        Self::BadRequest(rejection.body_text())
    }
}

impl From<PathRejection> for ApiError {
    fn from(rejection: PathRejection) -> Self {
        Self::BadRequest(rejection.body_text())
    }
}

impl IntoResponse for ApiError {
    fn into_response(self) -> Response {
        let (status, problem) = self.to_problem_details();
        if status == StatusCode::UNAUTHORIZED {
            return (
                status,
                [
                    (header::CONTENT_TYPE, "application/problem+json"),
                    (header::WWW_AUTHENTICATE, "Bearer"),
                ],
                Json(problem),
            )
                .into_response();
        }
        (status, [(header::CONTENT_TYPE, "application/problem+json")], Json(problem))
            .into_response()
    }
}

/// RFC 9457-compliant JSON extractor that converts `JsonRejection` into `application/problem+json`.
#[derive(Debug, Clone, Copy, Default, FromRequest)]
#[from_request(via(Json), rejection(ApiError))]
pub struct ProblemJson<T>(pub T);

/// RFC 9457-compliant UTF-8 String body extractor that converts `StringRejection` into `application/problem+json`.
#[derive(Debug, Clone, Default, FromRequest)]
#[from_request(rejection(ApiError))]
pub struct ProblemString(pub String);

/// RFC 9457-compliant Query extractor that converts `QueryRejection` into `application/problem+json`.
#[derive(Debug, Clone, Copy, Default, FromRequestParts)]
#[from_request(via(Query), rejection(ApiError))]
pub struct ProblemQuery<T>(pub T);

/// RFC 9457-compliant Path extractor that converts `PathRejection` into `application/problem+json`.
#[derive(Debug, Clone, Copy, Default, FromRequestParts)]
#[from_request(via(Path), rejection(ApiError))]
pub struct ProblemPath<T>(pub T);
