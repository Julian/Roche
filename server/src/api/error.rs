/// RFC 9457 §4.2.1 blank problem type URI for generic HTTP status responses.
pub const PROBLEM_TYPE_BLANK: &str = "about:blank";
/// Bearer token is unknown, malformed, or revoked.
pub const PROBLEM_TYPE_TOKEN_INVALID: &str = "urn:roche:problem:token-invalid";
/// Pairing code is missing, invalid, expired, or already consumed.
pub const PROBLEM_TYPE_PAIRING_CODE_INVALID: &str = "urn:roche:problem:pairing-code-invalid";
/// Client exceeded the pairing attempt rate limit; check `retry_after_seconds` / `Retry-After`.
pub const PROBLEM_TYPE_PAIRING_RATE_LIMITED: &str = "urn:roche:problem:pairing-rate-limited";
/// Request payload exceeded the route or batch size limit; check `max_bytes` when present.
pub const PROBLEM_TYPE_PAYLOAD_TOO_LARGE: &str = "urn:roche:problem:payload-too-large";
/// Catalog lookup matched multiple entries; check `candidates`.
pub const PROBLEM_TYPE_AMBIGUOUS_LOOKUP: &str = "urn:roche:problem:ambiguous-lookup";
/// Attempted manual membership mutation on a non-manual (dynamic/feed) collection.
pub const PROBLEM_TYPE_IMMUTABLE_COLLECTION: &str = "urn:roche:problem:immutable-collection";
/// Target URL was rejected by SSRF / outbound URL safety policy.
pub const PROBLEM_TYPE_SSRF_BLOCKED: &str = "urn:roche:problem:ssrf-blocked";
/// Resource conflict (such as duplicate unique identifier or slug).
pub const PROBLEM_TYPE_CONFLICT: &str = "urn:roche:problem:conflict";

/// Request extension recording the route's configured body limit in bytes so
/// `413 Payload Too Large` responses populate the RFC 9457 `max_bytes` extension member.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RouteBodyLimit(pub u64);

/// RFC 9457 Problem Details for HTTP APIs (`application/problem+json`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ProblemDetails {
    /// A URI reference that identifies the problem type.
    #[serde(rename = "type")]
    pub problem_type: String,
    /// A short, human-readable summary of the problem type.
    pub title: String,
    /// The HTTP status code generated by the origin server for this occurrence of the problem.
    pub status: u16,
    /// A human-readable explanation specific to this occurrence of the problem.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub detail: Option<String>,
    /// Suggested retry delay in seconds for rate-limited responses.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub retry_after_seconds: Option<u64>,
    /// Maximum allowed request payload size in bytes for `413 Payload Too Large` responses.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub max_bytes: Option<u64>,
    /// Candidate matches for `409 Ambiguous Lookup` responses.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub candidates: Option<Vec<String>>,
}

impl ProblemDetails {
    #[must_use]
    pub fn new(
        status: StatusCode,
        problem_type: &str,
        title: &str,
        detail: impl Into<String>,
    ) -> Self {
        Self {
            problem_type: problem_type.to_string(),
            title: title.to_string(),
            status: status.as_u16(),
            detail: Some(detail.into()),
            retry_after_seconds: None,
            max_bytes: None,
            candidates: None,
        }
    }

    #[must_use]
    pub const fn with_retry_after_seconds(mut self, retry_after_seconds: u64) -> Self {
        self.retry_after_seconds = Some(retry_after_seconds);
        self
    }

    #[must_use]
    pub const fn with_max_bytes(mut self, max_bytes: Option<u64>) -> Self {
        self.max_bytes = max_bytes;
        self
    }

    #[must_use]
    pub fn with_candidates(mut self, candidates: Vec<String>) -> Self {
        self.candidates = Some(candidates);
        self
    }
}

/// Structured HTTP API errors backed by `thiserror` and rendered as RFC 9457 Problem Details.
#[derive(Debug, Error)]
pub enum ApiError {
    #[error("Bad request: {0}")]
    BadRequest(String),

    #[error("Unauthorized: {0}")]
    Unauthorized(String),

    #[error("Forbidden: {0}")]
    Forbidden(String),

    #[error("Invalid bearer token: {0}")]
    TokenInvalid(String),

    #[error("Invalid pairing code: {0}")]
    PairingCodeInvalid(String),

    #[error("Pairing rate limited: {detail}")]
    PairingRateLimited { detail: String, retry_after_seconds: u64 },

    #[error("Not found: {0}")]
    NotFound(String),

    #[error("Conflict: {0}")]
    Conflict(String),

    #[error("Ambiguous lookup: {detail}")]
    AmbiguousLookup { detail: String, candidates: Vec<String> },

    #[error("Immutable collection: {0}")]
    ImmutableCollection(String),

    #[error("SSRF blocked: {0}")]
    SsrfBlocked(String),

    #[error("Method not allowed: {0}")]
    MethodNotAllowed(String),

    #[error("Payload too large: {detail}")]
    PayloadTooLarge { detail: String, max_bytes: Option<u64> },

    #[error("Unsupported media type: {0}")]
    UnsupportedMediaType(String),

    #[error("Request timeout: {0}")]
    RequestTimeout(String),

    #[error("Service unavailable: {0}")]
    ServiceUnavailable(String),

    #[error("Upstream fetch failed: {0}")]
    BadGateway(String),

    #[error("Database error: {0}")]
    Database(sqlx::Error),

    #[error("Internal error: {0}")]
    Internal(anyhow::Error),
}

impl ApiError {
    pub fn bad_request(message: impl Into<String>) -> Self {
        Self::BadRequest(message.into())
    }

    pub fn unauthorized(message: impl Into<String>) -> Self {
        Self::Unauthorized(message.into())
    }

    pub fn forbidden(message: impl Into<String>) -> Self {
        Self::Forbidden(message.into())
    }

    pub fn token_invalid(message: impl Into<String>) -> Self {
        Self::TokenInvalid(message.into())
    }

    pub fn pairing_code_invalid(message: impl Into<String>) -> Self {
        Self::PairingCodeInvalid(message.into())
    }

    pub fn pairing_rate_limited(detail: impl Into<String>, retry_after_seconds: u64) -> Self {
        Self::PairingRateLimited { detail: detail.into(), retry_after_seconds }
    }

    pub fn not_found(message: impl Into<String>) -> Self {
        Self::NotFound(message.into())
    }

    pub fn conflict(message: impl Into<String>) -> Self {
        Self::Conflict(message.into())
    }

    pub fn ambiguous_lookup(detail: impl Into<String>, candidates: Vec<String>) -> Self {
        Self::AmbiguousLookup { detail: detail.into(), candidates }
    }

    pub fn immutable_collection(message: impl Into<String>) -> Self {
        Self::ImmutableCollection(message.into())
    }

    pub fn ssrf_blocked(message: impl Into<String>) -> Self {
        Self::SsrfBlocked(message.into())
    }

    pub fn method_not_allowed(message: impl Into<String>) -> Self {
        Self::MethodNotAllowed(message.into())
    }

    pub fn payload_too_large(detail: impl Into<String>) -> Self {
        Self::PayloadTooLarge { detail: detail.into(), max_bytes: None }
    }

    pub fn payload_too_large_with_limit(detail: impl Into<String>, max_bytes: u64) -> Self {
        Self::PayloadTooLarge { detail: detail.into(), max_bytes: Some(max_bytes) }
    }

    pub fn request_timeout(message: impl Into<String>) -> Self {
        Self::RequestTimeout(message.into())
    }

    pub fn service_unavailable(message: impl Into<String>) -> Self {
        Self::ServiceUnavailable(message.into())
    }

    pub fn bad_gateway(message: impl Into<String>) -> Self {
        Self::BadGateway(message.into())
    }

    fn problem(
        status: StatusCode,
        problem_type: &str,
        title: &str,
        detail: impl Into<String>,
    ) -> (StatusCode, ProblemDetails) {
        (status, ProblemDetails::new(status, problem_type, title, detail))
    }

    #[must_use]
    #[allow(clippy::too_many_lines)]
    pub fn to_problem_details(&self) -> (StatusCode, ProblemDetails) {
        match self {
            Self::BadRequest(d) => {
                Self::problem(StatusCode::BAD_REQUEST, PROBLEM_TYPE_BLANK, "Bad Request", d.clone())
            }
            Self::Unauthorized(d) => Self::problem(
                StatusCode::UNAUTHORIZED,
                PROBLEM_TYPE_BLANK,
                "Unauthorized",
                d.clone(),
            ),
            Self::Forbidden(d) => {
                Self::problem(StatusCode::FORBIDDEN, PROBLEM_TYPE_BLANK, "Forbidden", d.clone())
            }
            Self::TokenInvalid(d) => Self::problem(
                StatusCode::UNAUTHORIZED,
                PROBLEM_TYPE_TOKEN_INVALID,
                "Invalid Token",
                d.clone(),
            ),
            Self::PairingCodeInvalid(d) => Self::problem(
                StatusCode::UNAUTHORIZED,
                PROBLEM_TYPE_PAIRING_CODE_INVALID,
                "Invalid Pairing Code",
                d.clone(),
            ),
            Self::PairingRateLimited { detail, retry_after_seconds } => (
                StatusCode::TOO_MANY_REQUESTS,
                ProblemDetails::new(
                    StatusCode::TOO_MANY_REQUESTS,
                    PROBLEM_TYPE_PAIRING_RATE_LIMITED,
                    "Pairing Rate Limited",
                    detail.clone(),
                )
                .with_retry_after_seconds(*retry_after_seconds),
            ),
            Self::NotFound(d) => {
                Self::problem(StatusCode::NOT_FOUND, PROBLEM_TYPE_BLANK, "Not Found", d.clone())
            }
            Self::Conflict(d) => {
                Self::problem(StatusCode::CONFLICT, PROBLEM_TYPE_CONFLICT, "Conflict", d.clone())
            }
            Self::AmbiguousLookup { detail, candidates } => (
                StatusCode::CONFLICT,
                ProblemDetails::new(
                    StatusCode::CONFLICT,
                    PROBLEM_TYPE_AMBIGUOUS_LOOKUP,
                    "Ambiguous Lookup",
                    detail.clone(),
                )
                .with_candidates(candidates.clone()),
            ),
            Self::ImmutableCollection(d) => Self::problem(
                StatusCode::BAD_REQUEST,
                PROBLEM_TYPE_IMMUTABLE_COLLECTION,
                "Immutable Collection",
                d.clone(),
            ),
            Self::SsrfBlocked(d) => Self::problem(
                StatusCode::BAD_REQUEST,
                PROBLEM_TYPE_SSRF_BLOCKED,
                "URL Target Blocked",
                d.clone(),
            ),
            Self::MethodNotAllowed(d) => Self::problem(
                StatusCode::METHOD_NOT_ALLOWED,
                PROBLEM_TYPE_BLANK,
                "Method Not Allowed",
                d.clone(),
            ),
            Self::PayloadTooLarge { detail, max_bytes } => (
                StatusCode::PAYLOAD_TOO_LARGE,
                ProblemDetails::new(
                    StatusCode::PAYLOAD_TOO_LARGE,
                    PROBLEM_TYPE_PAYLOAD_TOO_LARGE,
                    "Payload Too Large",
                    detail.clone(),
                )
                .with_max_bytes(*max_bytes),
            ),
            Self::UnsupportedMediaType(d) => Self::problem(
                StatusCode::UNSUPPORTED_MEDIA_TYPE,
                PROBLEM_TYPE_BLANK,
                "Unsupported Media Type",
                d.clone(),
            ),
            Self::RequestTimeout(d) => Self::problem(
                StatusCode::REQUEST_TIMEOUT,
                PROBLEM_TYPE_BLANK,
                "Request Timeout",
                d.clone(),
            ),
            Self::ServiceUnavailable(d) => Self::problem(
                StatusCode::SERVICE_UNAVAILABLE,
                PROBLEM_TYPE_BLANK,
                "Service Unavailable",
                d.clone(),
            ),
            Self::BadGateway(d) => {
                Self::problem(StatusCode::BAD_GATEWAY, PROBLEM_TYPE_BLANK, "Bad Gateway", d.clone())
            }
            Self::Database(sqlx_err) => {
                tracing::error!(error = %sqlx_err, "Database error");
                Self::problem(
                    StatusCode::INTERNAL_SERVER_ERROR,
                    PROBLEM_TYPE_BLANK,
                    "Internal Server Error",
                    "An unexpected database error occurred",
                )
            }
            Self::Internal(err) => {
                tracing::error!(error = %err, "Internal server error");
                Self::problem(
                    StatusCode::INTERNAL_SERVER_ERROR,
                    PROBLEM_TYPE_BLANK,
                    "Internal Server Error",
                    "An unexpected internal error occurred",
                )
            }
        }
    }

    fn from_json_rejection(rejection: JsonRejection, max_bytes: Option<u64>) -> Self {
        match rejection {
            JsonRejection::MissingJsonContentType(err) => {
                Self::UnsupportedMediaType(err.body_text())
            }
            JsonRejection::BytesRejection(err) if err.status() == StatusCode::PAYLOAD_TOO_LARGE => {
                max_bytes.map_or_else(
                    || Self::payload_too_large(err.body_text()),
                    |limit| Self::payload_too_large_with_limit(err.body_text(), limit),
                )
            }
            other => Self::bad_request(other.body_text()),
        }
    }

    fn from_string_rejection(rejection: &StringRejection, max_bytes: Option<u64>) -> Self {
        if rejection.status() == StatusCode::PAYLOAD_TOO_LARGE {
            max_bytes.map_or_else(
                || Self::payload_too_large(rejection.body_text()),
                |limit| Self::payload_too_large_with_limit(rejection.body_text(), limit),
            )
        } else {
            Self::bad_request(rejection.body_text())
        }
    }
}

impl From<JsonRejection> for ApiError {
    fn from(rejection: JsonRejection) -> Self {
        Self::from_json_rejection(rejection, None)
    }
}

impl From<StringRejection> for ApiError {
    fn from(rejection: StringRejection) -> Self {
        Self::from_string_rejection(&rejection, None)
    }
}

impl From<QueryRejection> for ApiError {
    fn from(rejection: QueryRejection) -> Self {
        Self::BadRequest(rejection.body_text())
    }
}

impl From<PathRejection> for ApiError {
    fn from(rejection: PathRejection) -> Self {
        Self::BadRequest(rejection.body_text())
    }
}

impl From<AppError> for ApiError {
    fn from(err: AppError) -> Self {
        match err {
            AppError::BadRequest(msg) => Self::bad_request(msg),
            AppError::Forbidden(msg) => Self::forbidden(msg),
            AppError::TokenInvalid(msg) => Self::token_invalid(msg),
            AppError::PairingCodeInvalid(msg) => Self::pairing_code_invalid(msg),
            AppError::PairingRateLimited { detail, retry_after_seconds } => {
                Self::pairing_rate_limited(detail, retry_after_seconds)
            }
            AppError::NotFound(msg) => Self::not_found(msg),
            AppError::Conflict(msg) => Self::conflict(msg),
            AppError::AmbiguousLookup { detail, candidates } => {
                Self::ambiguous_lookup(detail, candidates)
            }
            AppError::ImmutableCollection(msg) => Self::immutable_collection(msg),
            AppError::SsrfBlocked(msg) => Self::ssrf_blocked(msg),
            AppError::PayloadTooLarge { detail, max_bytes } => {
                Self::PayloadTooLarge { detail, max_bytes }
            }
            AppError::BadGateway(msg) => Self::bad_gateway(msg),
            AppError::Database(err) => Self::Database(err),
            AppError::Internal(err) => Self::Internal(err),
        }
    }
}

impl IntoResponse for ApiError {
    fn into_response(self) -> Response {
        let (status, problem) = self.to_problem_details();
        let retry_after = problem.retry_after_seconds;
        let mut resp = (status, Json(problem)).into_response();
        let headers = resp.headers_mut();
        headers.insert(header::CONTENT_TYPE, HeaderValue::from_static("application/problem+json"));
        if status == StatusCode::UNAUTHORIZED {
            headers.insert(header::WWW_AUTHENTICATE, HeaderValue::from_static("Bearer"));
        }
        if status == StatusCode::TOO_MANY_REQUESTS
            && let Some(secs) = retry_after
            && let Ok(val) = HeaderValue::from_str(&secs.to_string())
        {
            headers.insert(header::RETRY_AFTER, val);
        }
        resp
    }
}

/// RFC 9457-compliant JSON extractor that converts `JsonRejection` into `application/problem+json`
/// and attaches the route's configured [`RouteBodyLimit`] to `413 Payload Too Large` responses.
#[derive(Debug, Clone, Copy, Default)]
pub struct ProblemJson<T>(pub T);

impl<T, S> FromRequest<S> for ProblemJson<T>
where
    T: DeserializeOwned,
    S: Send + Sync,
{
    type Rejection = ApiError;

    async fn from_request(req: Request, state: &S) -> Result<Self, Self::Rejection> {
        let max_bytes = req.extensions().get::<RouteBodyLimit>().map(|limit| limit.0);
        match Json::<T>::from_request(req, state).await {
            Ok(Json(value)) => Ok(Self(value)),
            Err(rejection) => Err(ApiError::from_json_rejection(rejection, max_bytes)),
        }
    }
}

/// RFC 9457-compliant optional JSON extractor: treats empty/whitespace bodies as `T::default()`,
/// enforces `Content-Type: application/json` and [`RouteBodyLimit`] on non-empty bodies, and maps
/// rejections into `application/problem+json`.
#[derive(Debug, Clone, Copy, Default)]
pub struct OptionalProblemJson<T>(pub T);

impl<T, S> FromRequest<S> for OptionalProblemJson<T>
where
    T: DeserializeOwned + Default,
    S: Send + Sync,
{
    type Rejection = ApiError;

    async fn from_request(req: Request, state: &S) -> Result<Self, Self::Rejection> {
        let max_bytes = req.extensions().get::<RouteBodyLimit>().map(|limit| limit.0);
        let has_json_content_type =
            req.headers().get(header::CONTENT_TYPE).and_then(|v| v.to_str().ok()).is_some_and(
                |ct| {
                    ct.split(';')
                        .next()
                        .map(str::trim)
                        .is_some_and(|mime| mime.eq_ignore_ascii_case("application/json"))
                },
            );
        let bytes = match axum::body::Bytes::from_request(req, state).await {
            Ok(b) => b,
            Err(rejection) => {
                if rejection.status() == StatusCode::PAYLOAD_TOO_LARGE {
                    return Err(max_bytes.map_or_else(
                        || {
                            ApiError::payload_too_large(
                                "Request body exceeded maximum allowed size",
                            )
                        },
                        |limit| {
                            ApiError::payload_too_large_with_limit(
                                format!(
                                    "Request body exceeded maximum allowed size of {limit} bytes"
                                ),
                                limit,
                            )
                        },
                    ));
                }
                return Err(ApiError::bad_request(rejection.body_text()));
            }
        };
        if !bytes.iter().any(|b| !b.is_ascii_whitespace()) {
            return Ok(Self(T::default()));
        }
        if !has_json_content_type {
            return Err(ApiError::UnsupportedMediaType(
                "Expected request with `Content-Type: application/json`".to_owned(),
            ));
        }
        let parsed = serde_json::from_slice::<T>(&bytes)
            .map_err(|e| ApiError::bad_request(format!("Invalid JSON payload: {e}")))?;
        Ok(Self(parsed))
    }
}

/// RFC 9457-compliant UTF-8 String body extractor that converts `StringRejection` into
/// `application/problem+json` and attaches [`RouteBodyLimit`] to `413 Payload Too Large` responses.
#[derive(Debug, Clone, Default)]
pub struct ProblemString(pub String);

impl<S> FromRequest<S> for ProblemString
where
    S: Send + Sync,
{
    type Rejection = ApiError;

    async fn from_request(req: Request, state: &S) -> Result<Self, Self::Rejection> {
        let max_bytes = req.extensions().get::<RouteBodyLimit>().map(|limit| limit.0);
        match String::from_request(req, state).await {
            Ok(value) => Ok(Self(value)),
            Err(rejection) => Err(ApiError::from_string_rejection(&rejection, max_bytes)),
        }
    }
}

/// RFC 9457-compliant Query extractor that converts `QueryRejection` into `application/problem+json`.
#[derive(Debug, Clone, Copy, Default, FromRequestParts)]
#[from_request(via(Query), rejection(ApiError))]
pub struct ProblemQuery<T>(pub T);

/// RFC 9457-compliant Path extractor that converts `PathRejection` into `application/problem+json`.
